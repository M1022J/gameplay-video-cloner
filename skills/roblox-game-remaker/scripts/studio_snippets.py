#!/usr/bin/env python3
"""Generate Roblox Studio code from remake data, and digest Studio output.

Subcommands:
  greybox LAYOUT.json --out greybox.luau [--studs-per-meter X]
      Standalone Luau that (re)builds Workspace.Level_Greybox from a metric layout. Run it with
      MCP execute_luau (datamodel_type Edit), the command bar, or the Studio CLI RunScript task.
  shots SHOTS.json --out Shots.luau
      The Shots ModuleScript for ShotCamera hotkeys (F7/F8), from remake/shots.json.
  apply-shot SHOTS.json --id SHOT-03
      A client snippet (execute_luau datamodel_type Client, during play) that applies one shot.
  extract-log CONSOLE.txt --out run.log
      Keep only REMAKE_* lines from pasted Output / get_console_output text, with a summary
      (smoke test results, harness sample counts, input-probe events).
  inputs LOG [--out bindings.md]
      Turn InputProbe REMAKE_INPUT lines into a binding table for CTRL / VR entries.

Layout JSON (lengths in "unit": "studs" or "m"; position = part center; rotation in degrees):
  {"unit": "m", "parts": [{"name": "Floor", "size": [40, 1, 40], "position": [0, -0.5, 0],
    "rotation": [0, 0, 0], "color": "#6E8B5A", "material": "SmoothPlastic", "transparency": 0}],
   "spawn": [0, 1, 0]}
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import remake_common as rc  # noqa: E402

TOOL = "studio_snippets"
NAME_RE = re.compile(r"^[A-Za-z0-9_ .\-]{1,100}$")
STUDIO_SUFFIX_RE = re.compile(r"\s+-\s+(?:Server|Client|Edit|Studio)\b.*$")
MATERIALS = {"Plastic", "SmoothPlastic", "Wood", "WoodPlanks", "Brick", "Concrete", "Metal", "DiamondPlate", "Grass",
             "Sand", "Slate", "Granite", "Marble", "Pebble", "Cobblestone", "Ice", "Glass", "Neon", "Fabric", "Foil",
             "CorrodedMetal", "ForceField", "Asphalt", "Basalt", "CrackedLava", "Glacier", "Ground", "LeafyGrass",
             "Limestone", "Mud", "Pavement", "Rock", "Salt", "Sandstone", "Snow", "Cardboard", "Carpet",
             "CeramicTiles", "ClayRoofTiles", "RoofShingles", "Leather", "Plaster", "Rubber"}


def num(v, what: str) -> float:
    try:
        return float(v)
    except (TypeError, ValueError):
        rc.fail(f"{what} must be a number (got {v!r})")


def vec(v, what: str, scale: float = 1.0) -> list[float]:
    if not isinstance(v, (list, tuple)) or len(v) != 3:
        rc.fail(f"{what} must be [x, y, z]")
    return [num(x, what) * scale for x in v]


def luau_num(x: float) -> str:
    return f"{x:.6g}"


def hex_rgb(h: str, what: str) -> tuple[int, int, int]:
    m = re.fullmatch(r"#?([0-9a-fA-F]{6})", h or "")
    if not m:
        rc.fail(f"{what} must be a #RRGGBB color (got {h!r})")
    v = m.group(1)
    return int(v[0:2], 16), int(v[2:4], 16), int(v[4:6], 16)


def cmd_greybox(args) -> int:
    layout = rc.read_json(args.layout)
    unit = layout.get("unit", "studs")
    if unit not in ("studs", "m"):
        rc.fail('layout "unit" must be "studs" or "m"')
    scale = args.studs_per_meter if unit == "m" else 1.0
    if unit == "m" and not scale:
        rc.fail('layout is in meters: pass --studs-per-meter (Config.World.StudsPerMeter, e.g. 3.5714)')
    parts = layout.get("parts")
    if not isinstance(parts, list) or not parts:
        rc.fail("layout needs a non-empty 'parts' list")
    names = set()
    lines = [
        f"-- Generated by studio_snippets.py greybox from {args.layout.name} ({len(parts)} parts, unit {unit}"
        + (f", {scale:g} studs/m" if unit == "m" else "") + ").",
        "-- Rebuilds Workspace.Level_Greybox; safe to run again. MCP: execute_luau with datamodel_type Edit.",
        'local Workspace = game:GetService("Workspace")',
        'local existing = Workspace:FindFirstChild("Level_Greybox")',
        "if existing then",
        "\texisting:Destroy()",
        "end",
        'local folder = Instance.new("Folder")',
        'folder.Name = "Level_Greybox"',
        "local function part(name, size, cframe, color, material, transparency)",
        '\tlocal p = Instance.new("Part")',
        "\tp.Name = name",
        "\tp.Anchored = true",
        "\tp.Size = size",
        "\tp.CFrame = cframe",
        "\tp.Color = color",
        "\tp.Material = material",
        "\tp.Transparency = transparency",
        "\tp.TopSurface = Enum.SurfaceType.Smooth",
        "\tp.BottomSurface = Enum.SurfaceType.Smooth",
        "\tp.Parent = folder",
        "\treturn p",
        "end",
    ]
    for i, p in enumerate(parts):
        name = str(p.get("name") or f"Part{i + 1}")
        if not NAME_RE.match(name):
            rc.fail(f"part name {name!r} has unsupported characters")
        if name in names:
            name = f"{name}_{i + 1}"
        names.add(name)
        size = vec(p.get("size"), f"{name}.size", scale)
        if min(size) <= 0:
            rc.fail(f"{name}.size must be positive")
        pos = vec(p.get("position"), f"{name}.position", scale)
        rot = vec(p.get("rotation", [0, 0, 0]), f"{name}.rotation")
        r, g, b = hex_rgb(p.get("color", "#A3A2A5"), f"{name}.color")
        material = p.get("material", "SmoothPlastic")
        if material not in MATERIALS:
            rc.fail(f"{name}.material {material!r} is not a known Enum.Material name")
        tr = num(p.get("transparency", 0), f"{name}.transparency")
        cf = f"CFrame.new({', '.join(map(luau_num, pos))})"
        if any(rot):
            cf += f" * CFrame.fromOrientation(math.rad({luau_num(rot[0])}), math.rad({luau_num(rot[1])}), math.rad({luau_num(rot[2])}))"
        lines.append(f'part("{name}", Vector3.new({", ".join(map(luau_num, size))}), {cf}, '
                     f"Color3.fromRGB({r}, {g}, {b}), Enum.Material.{material}, {luau_num(tr)})")
    if layout.get("spawn"):
        sp = vec(layout["spawn"], "spawn", scale)
        lines += ['local spawn = Instance.new("SpawnLocation")', 'spawn.Name = "RemakeSpawn"', "spawn.Anchored = true",
                  "spawn.Size = Vector3.new(4, 1, 4)", f"spawn.CFrame = CFrame.new({', '.join(map(luau_num, sp))})",
                  "spawn.Parent = folder"]
    lines += ["folder.Parent = Workspace", f'print("Level_Greybox built: " .. #folder:GetChildren() .. " instances")',
              "return #folder:GetChildren()"]
    rc.ensure_parent(args.out)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}: {len(parts)} parts" + (" + spawn" if layout.get("spawn") else ""))
    return 0


def load_shots(path: Path) -> list[dict]:
    data = rc.read_json(path)
    shots = data.get("shots") if isinstance(data, dict) else None
    if not isinstance(shots, list):
        rc.fail(f"{path} has no 'shots' list")
    out = []
    for s in shots:
        cam = s.get("camera") or {}
        if "position" not in cam or "look_at" not in cam:
            rc.fail(f"shot {s.get('id')} needs camera.position and camera.look_at")
        out.append(s)
    return out


def shot_table(s: dict) -> str:
    cam = s["camera"]
    pos = ", ".join(map(luau_num, vec(cam["position"], "position")))
    look = ", ".join(map(luau_num, vec(cam["look_at"], "look_at")))
    parts = [f'id = "{s.get("id", "")}"', f"position = Vector3.new({pos})", f"lookAt = Vector3.new({look})"]
    if cam.get("fov") is not None:
        parts.append(f"fov = {luau_num(num(cam['fov'], 'fov'))}")
    if s.get("clock_time") is not None:
        parts.append(f"clockTime = {luau_num(num(s['clock_time'], 'clock_time'))}")
    parts.append("hideGui = true")
    return "{ " + ", ".join(parts) + " }"


def cmd_shots(args) -> int:
    shots = load_shots(args.shots)
    lines = ["--!strict", f"-- Generated by studio_snippets.py shots from {args.shots.name}. ShotCamera hotkeys: F7 next, F8 release.",
             "local Shots: { { [string]: any } } = {"]
    lines += [f"\t{shot_table(s)}," for s in shots]
    lines += ["}", "", "return Shots"]
    rc.ensure_parent(args.out)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}: {len(shots)} shots (place it at ReplicatedStorage.Shared.Remake.Shots)")
    return 0


def cmd_apply_shot(args) -> int:
    shots = {s.get("id"): s for s in load_shots(args.shots)}
    if args.id not in shots:
        rc.fail(f"no shot {args.id!r}; known: {', '.join(map(str, shots))}")
    print("-- execute_luau datamodel_type Client (during play); then screen_capture, then ShotCamera.release()")
    print('local Players = game:GetService("Players")')
    print('local ShotCamera = require(Players.LocalPlayer:WaitForChild("PlayerScripts"):WaitForChild("Remake"):WaitForChild("ShotCamera"))')
    print(f"ShotCamera.apply({shot_table(shots[args.id])})")
    return 0


def cmd_extract_log(args) -> int:
    try:
        text = args.console.read_text(encoding="utf-8", errors="replace")
    except FileNotFoundError:
        rc.fail(f"not found: {args.console}")
    keep, counts = [], defaultdict(int)
    smoke = {"pass": [], "fail": [], "summary": None}
    for line in text.splitlines():
        m = re.search(r"\b(REMAKE_[A-Z]+)\b", line)
        if not m:
            continue
        tag = m.group(1)
        counts[tag] += 1
        line = STUDIO_SUFFIX_RE.sub("", line[m.start():]).rstrip()  # drop "  -  Server - Script:12"
        keep.append(line)
        if tag == "REMAKE_SMOKE":
            body = line[len(tag):].strip()
            if body.startswith("PASS"):
                smoke["pass"].append(body[4:].strip())
            elif body.startswith("FAIL"):
                smoke["fail"].append(body[4:].strip())
            elif body.startswith("SUMMARY"):
                smoke["summary"] = body[7:].strip()
    if not keep:
        rc.fail("no REMAKE_* lines found; enable the harness or probe, or copy the full Output", rc.EXIT_FAIL)
    rc.ensure_parent(args.out)
    args.out.write_text("\n".join(keep) + "\n", encoding="utf-8")
    print(f"wrote {args.out}: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))
    if counts.get("REMAKE_SMOKE"):
        print(f"smoke: {len(smoke['pass'])} pass, {len(smoke['fail'])} fail" + (f" ({smoke['summary']})" if smoke["summary"] else ""))
        for f in smoke["fail"]:
            print(f"  FAIL {f}")
    return rc.EXIT_FAIL if smoke["fail"] else 0


def cmd_inputs(args) -> int:
    try:
        text = args.log.read_text(encoding="utf-8", errors="replace")
    except FileNotFoundError:
        rc.fail(f"not found: {args.log}")
    decoder = json.JSONDecoder()
    seen: dict[tuple[str, str], dict] = {}
    session = None
    for line in text.splitlines():
        pos = line.find("REMAKE_INPUT")
        if pos < 0:
            continue
        brace = line.find("{", pos)
        try:
            obj, _ = decoder.raw_decode(line[brace:])
        except (json.JSONDecodeError, ValueError):
            continue
        if obj.get("e") == "session":
            session = obj
            continue
        key = (obj.get("kc", "?"), obj.get("ut", "?"))
        row = seen.setdefault(key, {"events": set(), "max_abs": [0.0, 0.0, 0.0], "processed": False})
        row["events"].add(obj.get("e"))
        for i, v in enumerate(obj.get("pos", [0, 0, 0])[:3]):
            row["max_abs"][i] = max(row["max_abs"][i], abs(float(v)))
        row["processed"] |= bool(obj.get("gp"))
    if not seen:
        rc.fail("no REMAKE_INPUT events found (enable DevTools/InputProbe and press every control)", rc.EXIT_FAIL)
    lines = ["<!-- studio_snippets.py inputs; cite the source log as evidence (type: capture) -->", ""]
    if session:
        lines.append(f"Session: {json.dumps(session.get('device', {}))}, preferred input {session.get('preferred')}")
        lines.append("")
    lines += ["| KeyCode | UserInputType | Events | Analog range (max abs x, y, z) | Game-processed |", "|---|---|---|---|---|"]
    for (kc, ut), r in sorted(seen.items()):
        analog = ", ".join(f"{v:.2f}" for v in r["max_abs"]) if any(r["max_abs"]) else "-"
        lines.append(f"| {kc} | {ut} | {', '.join(sorted(r['events']))} | {analog} | {'yes' if r['processed'] else 'no'} |")
    out = "\n".join(lines) + "\n"
    if args.out:
        rc.ensure_parent(args.out)
        args.out.write_text(out, encoding="utf-8")
    print(out)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("greybox")
    p.add_argument("layout", type=Path)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--studs-per-meter", type=float)
    p.set_defaults(fn=cmd_greybox)
    p = sub.add_parser("shots")
    p.add_argument("shots", type=Path)
    p.add_argument("--out", type=Path, required=True)
    p.set_defaults(fn=cmd_shots)
    p = sub.add_parser("apply-shot")
    p.add_argument("shots", type=Path)
    p.add_argument("--id", required=True)
    p.set_defaults(fn=cmd_apply_shot)
    p = sub.add_parser("extract-log")
    p.add_argument("console", type=Path)
    p.add_argument("--out", type=Path, required=True)
    p.set_defaults(fn=cmd_extract_log)
    p = sub.add_parser("inputs")
    p.add_argument("log", type=Path)
    p.add_argument("--out", type=Path)
    p.set_defaults(fn=cmd_inputs)
    args = ap.parse_args()
    return args.fn(args)


if __name__ == "__main__":
    rc.run_main(main)
